#!/usr/bin/env node
// Writes the "What it implements" section of each plugin's README from plugin.yaml, the hook contracts and the
// docblocks in the plugin's code, the way Drupal documented each hook implementation in a docblock and the module page
// listed them. --check fails when a README is out of date or a docblock is missing (also enforced by the validator).
// Usage: node scripts/plugin-docs.mjs [plugin folders...] [--check]
// Docblock convention (spec/02, "Documenting what a plugin implements"): the first line of the /** */ block above the
// implementation is one of
//   Implements hook <hook name>.
//   Implements operation <operationId>.
//   Implements contract <contract name>, operation <operation>.
//   Implements schedule <schedule id>.
//   Implements upgrade <version>.
// then a blank line, then what this implementation does and why (its first sentence goes in the README table), then
// @param / @returns lines.
import { readFileSync, writeFileSync, existsSync, readdirSync, statSync } from "node:fs";
import { join, dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { parse } from "yaml";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const contracts = Object.fromEntries(JSON.parse(readFileSync(join(root, "schema/hook-contracts.json"), "utf8")).map((c) => [c.name, c]));
const coreContracts = parse(readFileSync(join(root, "schema/core-contracts.yaml"), "utf8")).contracts;
const readAny = (f) => (f.endsWith(".json") ? JSON.parse(readFileSync(f, "utf8")) : parse(readFileSync(f, "utf8")));
const walk = (d) => (existsSync(d) ? readdirSync(d).flatMap((n) => (statSync(join(d, n)).isDirectory() ? (n === "vendor" ? [] : walk(join(d, n))) : [join(d, n)])) : []);
const START = "<!-- implements:start (generated by scripts/plugin-docs.mjs from plugin.yaml and the docblocks in the code; do not edit by hand) -->";
const END = "<!-- implements:end -->";

/** Every "Implements ..." docblock in a runtime's source: key -> first sentence of its description. */
// the code right after a docblock must be the thing it documents, so a block left behind after a refactor fails
const camelHook = (n) => n.split(".").map((x, i) => (i ? x[0].toUpperCase() + x.slice(1) : x)).join("");
function placedOn(key, next, handlers) {
  const [kind, rest] = [key.slice(0, key.indexOf(":")), key.slice(key.indexOf(":") + 1)];
  if (kind === "hook") return next.includes(`"${rest}"`) || next.includes(`'${rest}'`) || new RegExp(`function\\s+${camelHook(rest)}\\s*\\(`).test(next);
  if (kind === "operation") return new RegExp(`\\b${rest}\\b`).test(next);
  if (kind === "contract") { const [c, op] = rest.split("#"); return new RegExp(`\\b(async\\s+)?${op}\\s*\\(|function\\s+${camelHook(c)}${op[0].toUpperCase()}${op.slice(1)}\\s*\\(|["']${c}["']`).test(next); }
  if (kind === "schedule") { const h = (handlers || {})[rest] || rest; return new RegExp(`\\b${h}\\b`).test(next); }
  if (kind === "upgrade") return next.includes(rest.replace(/\./g, "_")) || next.includes(rest);
  return true;
}
export function docblocks(dir, rt, handlers = {}) {
  const out = {};
  for (const f of walk(join(dir, "src", rt)).filter((x) => /\.(m?js|cjs|php)$/.test(x))) {
    const src = readFileSync(f, "utf8");
    for (const m of src.matchAll(/\/\*\*([\s\S]*?)\*\//g)) {
      const next = (src.slice(m.index + m[0].length).split("\n").map((l) => l.trim()).find((l) => l && !l.startsWith("//")) || "");
      const lines = m[1].split("\n").map((l) => l.replace(/^\s*\*\s?/, "").trimEnd());
      while (lines.length && !lines[0].trim()) lines.shift();
      const head = (lines[0] || "").trim();
      let key = null;
      let mm;
      if ((mm = /^Implements hook ([a-z0-9-]+(?:\.[a-zA-Z0-9]+)+)\.?$/.exec(head))) key = `hook:${mm[1]}`;
      else if ((mm = /^Implements operation (\w+)\b/.exec(head))) key = `operation:${mm[1]}`;
      else if ((mm = /^Implements contract ([a-z0-9.-]+), operation (\w+)\b/.exec(head))) key = `contract:${mm[1]}#${mm[2]}`;
      else if ((mm = /^Implements schedule ([a-z0-9-]+)\b/.exec(head))) key = `schedule:${mm[1]}`;
      else if ((mm = /^Implements upgrade ([0-9.]+)\b/.exec(head))) key = `upgrade:${mm[1]}`;
      if (!key) continue;
      if (!placedOn(key, next, handlers)) continue;
      const desc = [];
      for (const l of lines.slice(1)) { if (l.trim().startsWith("@")) break; if (!l.trim() && desc.length) break; if (l.trim()) desc.push(l.trim()); }
      const text = desc.join(" ");
      out[key] = (/^(.+?[.!?])(\s|$)/.exec(text) || [null, text])[1];
    }
  }
  return out;
}

/** What a plugin must document: one entry per hook, operation, contract operation, schedule and upgrade. */
export function implementations(dir, m) {
  const list = [];
  for (const h of m.hooks || []) list.push({ key: `hook:${h.name}`, kind: "hook", name: h.name, h });
  if (m.openapi && existsSync(join(dir, m.openapi))) {
    const api = readAny(join(dir, m.openapi));
    for (const [path, verbs] of Object.entries(api.paths || {})) for (const [verb, op] of Object.entries(verbs)) {
      if (!op || !op.operationId) continue;
      list.push({ key: `operation:${op.operationId}`, kind: op["x-hax-proxy"] ? "proxy" : "operation", name: op.operationId, verb: verb.toUpperCase(), path, op, scope: op["x-hax-scope"] || api["x-hax-scope"] || "site" });
    }
  }
  for (const e of m.implements || []) {
    const name = typeof e === "string" ? e : e.name;
    for (const opName of (coreContracts[name] || {}).operations || []) list.push({ key: `contract:${name}#${opName}`, kind: "contract", name, opName, accepts: e.accepts });
  }
  for (const s of m.schedules || []) list.push({ key: `schedule:${s.id}`, kind: "schedule", name: s.id, s });
  return list;
}

const esc = (s) => String(s ?? "").replace(/\|/g, "\\|").replace(/\n/g, " ");
const when = (i) => {
  if (i.kind === "hook") { const c = contracts[i.name]; return c ? `${c.when}${i.h.detached ? " (detached)" : ""}${i.h.stage ? ` (stage ${i.h.stage})` : ""}` : "a hook another plugin defines"; }
  if (i.kind === "operation" || i.kind === "proxy") { const sec = (i.op.security || []).map((r) => Object.keys(r).join(" + ") || "anonymous").join(" or ") || (i.op["x-hax-public"] ? "public" : ""); return `\`${i.verb} ${i.scope === "system" ? "/system/api" : "/x/api"}/v1/plugins/<id>${i.path}\`${sec ? ` (${sec})` : ""}`; }
  if (i.kind === "contract") return `core calls it (${(coreContracts[i.name] || {}).dispatch || "all"}${i.accepts ? `: ${i.accepts.join(", ")}` : ""})`;
  if (i.kind === "schedule") return `\`${i.s.cron}\``;
  return "";
};

function section(dir, m) {
  const rows = [];
  const handlers = Object.fromEntries((m.schedules || []).map((x) => [x.id, x.handler]));
  const docs = { ...docblocks(dir, "php", handlers), ...docblocks(dir, "nodejs", handlers) };
  for (const i of implementations(dir, m)) {
    const what = i.kind === "proxy" ? `No code: core forwards to \`${new URL(String(i.op["x-hax-proxy"].url).replace(/\{\{[^}]+\}\}/g, "x")).host}\` with the declared query (${(i.op["x-hax-proxy"].pass || []).join(", ") || "nothing"} passed through).` : docs[i.key] || (i.kind === "operation" && i.op.summary) || "";
    const name = i.kind === "contract" ? `\`${i.name}\` ${i.opName}` : `\`${i.name}\``;
    rows.push(`| ${i.kind === "proxy" ? "operation (proxy)" : i.kind} | ${name} | ${esc(when(i))} | ${esc(what)} |`);
  }
  // registries: what the plugin adds without code
  const reg = (sub, label, key) => { for (const f of walk(join(dir, "registries", sub)).filter((x) => /\.(json|ya?ml)$/.test(x))) { const d = readAny(f); for (const e of d.apps || [d]) rows.push(`| ${label} | \`${esc(key(e))}\` | ${sub === "elements" ? esc(e.role || "") : ""} | ${esc((e.details && e.details.description) || e.description || e.summary || e.label || e.name || "")} |`); } };
  reg("elements", "element", (e) => e.tag);
  reg("themes", "theme", (e) => e.element);
  reg("skeletons", "skeleton", (e) => e.id || e.name || "skeleton");
  reg("appstore", "appstore app", (e) => (e.details && e.details.title) || "app");
  reg("dashboard", "dashboard", (e) => e.id);
  reg("cli", "CLI command", (e) => `hax ${m.id} ${e.command}${e.alias ? ` (hax ${e.alias})` : ""}`);
  reg("merlin", "Merlin", (e) => e.id || e.title || "program");
  if (!rows.length) return null;
  return [START, "## What it implements", "", "| Kind | Name | Runs when | What this plugin does |", "|---|---|---|---|", ...rows, "", ...(Object.keys(m.entry || {}).length ? [`Each code row matches a docblock (\`Implements hook ...\`, \`Implements operation ...\`) directly above the implementation in ${Object.keys(m.entry).map((rt) => `\`src/${rt}\``).join(" and ")}.`] : []), END].join("\n");
}

/** Missing docblocks for a plugin: "<runtime>: <key>" strings. */
export function missingDocblocks(dir, m) {
  const out = [];
  for (const rt of Object.keys(m.entry || {})) {
    const have = docblocks(dir, rt, Object.fromEntries((m.schedules || []).map((x) => [x.id, x.handler])));
    for (const i of implementations(dir, m)) if (i.kind !== "proxy" && !have[i.key]) out.push(`${rt}: no "Implements ${i.key.replace(/^contract:(.+)#(.+)$/, "contract $1, operation $2").replace(/^(\w+):/, "$1 ")}" docblock directly above its implementation`);
  }
  return out;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2);
  const check = args.includes("--check");
  let dirs = args.filter((a) => !a.startsWith("--")).map((d) => resolve(d));
  if (!dirs.length) dirs = ["examples", "core-plugins", "contrib-plugins"].flatMap((g) => (existsSync(join(root, g)) ? readdirSync(join(root, g)).map((n) => join(root, g, n)).filter((d) => existsSync(join(d, "plugin.yaml"))) : []));
  let bad = 0;
  for (const dir of dirs) {
    const m = parse(readFileSync(join(dir, "plugin.yaml"), "utf8"));
    const miss = missingDocblocks(dir, m);
    for (const x of miss) { console.log(`FAIL ${m.id}: ${x}`); bad++; }
    const sec = section(dir, m);
    const rp = join(dir, (m.docs && m.docs.readme) || "README.md");
    if (!sec || !existsSync(rp)) continue;
    const cur = readFileSync(rp, "utf8");
    const re = /<!-- implements:start[\s\S]*?<!-- implements:end -->/;
    const next = re.test(cur) ? cur.replace(re, sec) : `${cur.trimEnd()}\n\n${sec}\n`;
    if (next === cur) continue;
    if (check) { console.log(`FAIL ${m.id}: README "What it implements" is out of date (run node scripts/plugin-docs.mjs)`); bad++; }
    else { writeFileSync(rp, next); console.log(`wrote ${m.id}`); }
  }
  if (check) console.log(bad ? `FAIL plugin docs: ${bad} problem(s)` : `ok   plugin docs: ${dirs.length} plugins documented`);
  process.exit(bad && check ? 1 : 0);
}
