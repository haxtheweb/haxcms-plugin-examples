#!/usr/bin/env node
// Writes the full hook contract table into spec/06 from schema/hook-contracts.json. --check fails if it is out of date.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const contracts = JSON.parse(readFileSync(join(root, "schema/hook-contracts.json"), "utf8"));
const hooks = JSON.parse(readFileSync(join(root, "schema/hooks.json"), "utf8"));
const names = contracts.map((c) => c.name);
if (JSON.stringify(names) !== JSON.stringify(hooks)) { console.log("FAIL hooks.json and hook-contracts.json differ"); process.exit(1); }
const esc = (s) => s.replace(/\|/g, "\\|");
const rows = contracts.map((c) => `| \`${c.name}\` | ${esc(c.when)} | ${esc(c.subject)} | ${esc(c.previous)} | ${esc(c.returns)} | ${c.veto ? "yes" : "no"} | ${c.phase === "after" ? (c.detachable ? "yes" : "no") : "n/a"} |`);
const table = ["<!-- hook-table:start (generated by scripts/hook-table.mjs from schema/hook-contracts.json; do not edit by hand) -->",
  "| Hook | Fires when | `ctx.subject` | `ctx.previous` | Returns | Can veto | Can detach |",
  "|---|---|---|---|---|---|---|", ...rows, "<!-- hook-table:end -->"].join("\n");
const p = join(root, "spec/06-hooks-and-contracts.md");
const s = readFileSync(p, "utf8");
const re = /<!-- hook-table:start[\s\S]*?<!-- hook-table:end -->/;
if (!re.test(s)) { console.log("FAIL spec/06 has no hook-table markers"); process.exit(1); }
const next = s.replace(re, table);
if (process.argv.includes("--check")) { const ok = next === s; console.log(`${ok ? "ok  " : "FAIL"} hook table in spec/06 ${ok ? "matches" : "is out of date; run node scripts/hook-table.mjs"} (${contracts.length} hooks)`); process.exit(ok ? 0 : 1); }
writeFileSync(p, next); console.log(`wrote ${contracts.length} hooks to spec/06`);
